"""Shared loading, validation, and rendering for the harness.

Used by validate.py, sync.py, doctor.py, and tests/test_harness.py.
The source of truth is src/. Generated bindings are never edited by hand.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
GENERATED_MARK = "GENERATED by src/cli/sync.py — do not hand-edit"
REQUIRED_FIELDS = ("id", "version", "status", "origin", "audience")
STATUSES = {"draft", "active", "deprecated"}
ORIGINS = {"authored", "referenced"}
AUDIENCES = {"human", "agent", "both"}
PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z_]\w*)\s*\}\}")


class HarnessError(Exception):
    """A rule violation that stops rendering."""


@dataclass
class Artifact:
    rel: Path  # path relative to the repo root, e.g. src/agents/x.md
    meta: dict
    body: str

    @property
    def id(self):
        return self.meta.get("id")

    @property
    def folder(self) -> str:
        return self.rel.parts[1]


def split_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end == -1:
        raise HarnessError("unterminated frontmatter")
    meta = yaml.safe_load(text[4:end]) or {}
    return meta, text[end + 4 :].lstrip("\n")


def iter_artifacts(root: Path = REPO_ROOT) -> list[Artifact]:
    """Every validated markdown file under src/. README.md and _-prefixed templates are skipped."""
    found = []
    for path in sorted((root / "src").rglob("*.md")):
        if path.name == "README.md" or path.name.startswith("_"):
            continue
        meta, body = split_frontmatter(path.read_text())
        found.append(Artifact(path.relative_to(root), meta, body))
    return found


def validate_artifacts(artifacts: list[Artifact]) -> list[str]:
    errors: list[str] = []
    by_id: dict[str, Artifact] = {}

    for a in artifacts:
        where = str(a.rel)
        if not a.meta:
            errors.append(f"{where}: missing frontmatter")
            continue
        for field in REQUIRED_FIELDS:
            if field not in a.meta:
                errors.append(f"{where}: missing '{field}'")
        if a.meta.get("status") not in STATUSES:
            errors.append(f"{where}: status must be one of {sorted(STATUSES)}")
        if a.meta.get("origin") not in ORIGINS:
            errors.append(f"{where}: origin must be one of {sorted(ORIGINS)}")
        if a.meta.get("audience") not in AUDIENCES:
            errors.append(f"{where}: audience must be one of {sorted(AUDIENCES)}")
        if a.meta.get("origin") == "referenced" and not a.meta.get("source"):
            errors.append(f"{where}: origin 'referenced' requires 'source'")
        level = a.meta.get("level")
        if level is not None and level not in range(1, 9):
            errors.append(f"{where}: level must be 1-8")
        if a.folder == "agents" and not a.meta.get("description"):
            errors.append(f"{where}: agents require 'description'")
        if a.id is not None:
            if a.id in by_id:
                errors.append(
                    f"{where}: duplicate id '{a.id}' (also {by_id[a.id].rel})"
                )
            by_id[a.id] = a

    for a in artifacts:
        where = str(a.rel)
        if not a.meta:
            continue
        for dep in a.meta.get("implements") or []:
            if dep not in by_id:
                errors.append(f"{where}: implements unknown id '{dep}'")
        params = a.meta.get("parameters") or {}
        for name, spec in params.items():
            if not isinstance(spec, dict) or "default" not in spec:
                errors.append(f"{where}: parameter '{name}' needs a default")
                continue
            allowed = spec.get("allowed")
            if allowed is not None and spec["default"] not in allowed:
                errors.append(f"{where}: default for '{name}' is not in allowed")
        for name in sorted(set(PLACEHOLDER.findall(a.body)) - set(params)):
            errors.append(
                f"{where}: placeholder '{{{{{name}}}}}' is not a declared parameter"
            )
    return errors


def render(a: Artifact, overrides: dict | None = None) -> str:
    """Render an agent for a binding. Overrides may only name declared parameters, within allowed values."""
    overrides = dict(overrides or {})
    params = a.meta.get("parameters") or {}

    unknown = set(overrides) - set(params)
    if unknown:
        raise HarnessError(f"{a.id}: undeclared parameter(s) {sorted(unknown)}")

    values = {}
    for name, spec in params.items():
        value = overrides.get(name, spec["default"])
        allowed = spec.get("allowed")
        if allowed is not None and value not in allowed:
            raise HarnessError(f"{a.id}: {name}={value!r} is not in {allowed}")
        values[name] = value

    description = a.meta.get("description")
    if not description:
        raise HarnessError(f"{a.id}: agents require 'description'")

    body = PLACEHOLDER.sub(lambda m: str(values[m.group(1)]), a.body)
    front = yaml.safe_dump(
        {"name": a.id, "description": description}, sort_keys=False, width=10**6
    )
    return f"---\n{front}---\n<!-- {GENERATED_MARK} -->\n\n{body}"


def desired_outputs(root: Path = REPO_ROOT) -> dict[Path, str]:
    """Map each generated binding path to its expected contents. Only agents for now."""
    out = {}
    for a in iter_artifacts(root):
        if a.folder != "agents" or a.meta.get("status") == "deprecated":
            continue
        out[root / ".claude" / "agents" / f"{a.id}.md"] = render(a)
    return out


def _orphans(root: Path, want: dict[Path, str]) -> list[Path]:
    agents_dir = root / ".claude" / "agents"
    if not agents_dir.exists():
        return []
    return [
        p
        for p in agents_dir.glob("*.md")
        if p not in want and GENERATED_MARK in p.read_text()
    ]


def drift(root: Path = REPO_ROOT) -> list[tuple[str, Path]]:
    want = desired_outputs(root)
    problems: list[tuple[str, Path]] = []
    for path, text in want.items():
        if not path.exists():
            problems.append(("missing", path))
        elif path.read_text() != text:
            problems.append(("stale", path))
    problems += [("orphan", p) for p in _orphans(root, want)]
    return problems


def write_outputs(root: Path = REPO_ROOT) -> int:
    want = desired_outputs(root)
    for path, text in want.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    for path in _orphans(root, want):
        path.unlink()
    return len(want)
