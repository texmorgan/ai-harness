"""Shared helpers for the AI-harness CLI scripts."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

import yaml

# ── paths ──────────────────────────────────────────────────────
REPO_ROOT = Path(__file__).resolve().parent.parent

SKILLS_DIR = REPO_ROOT / "skills"
POWERS_DIR = REPO_ROOT / "powers"
STEERING_DIR = REPO_ROOT / "steering"
CONVENTIONS = REPO_ROOT / "conventions"
DOCS_DIR = REPO_ROOT / "docs"
MCP_DIR = REPO_ROOT / "mcp"

SKILLS_REGISTRY = SKILLS_DIR / "_registry.yaml"
POWERS_INDEX = POWERS_DIR / "_index.yaml"
STEERING_INDEX = STEERING_DIR / "_index.yaml"

GENERATED_HEADER = "<!-- GENERATED by scripts/sync.py — do not hand-edit -->"
GENERATED_HEADER_YAML = "# GENERATED by scripts/sync.py — do not hand-edit"

# ── data shapes ────────────────────────────────────────────────


@dataclass
class Skill:
    id: str
    version: str
    tags: list[str]
    triggers: list[str]
    targets: dict
    requires: dict
    skill_md_path: Path | None = None
    context_md_path: Path | None = None

    @classmethod
    def from_yaml(cls, raw: dict) -> Skill:
        skill_id = raw["id"]
        skill_dir = SKILLS_DIR / skill_id
        return cls(
            id=skill_id,
            version=str(raw.get("version", "0.1")),
            tags=raw.get("tags", []),
            triggers=raw.get("triggers", []),
            targets=raw.get("targets", {}),
            requires=raw.get("requires", {}),
            skill_md_path=skill_dir / "SKILL.md"
            if (skill_dir / "SKILL.md").exists()
            else None,
            context_md_path=skill_dir / "context.md"
            if (skill_dir / "context.md").exists()
            else None,
        )


@dataclass
class Power:
    id: str
    file: str
    composes: dict
    permissions: list[str]
    not_permitted: list[str]
    md_path: Path | None = None

    @classmethod
    def from_yaml(cls, raw: dict) -> Power:
        power_id = raw["id"]
        md = POWERS_DIR / raw.get("file", f"{power_id}.md")
        return cls(
            id=power_id,
            file=raw.get("file", f"{power_id}.md"),
            composes=raw.get("composes", {}),
            permissions=raw.get("permissions", []),
            not_permitted=raw.get("not_permitted", []),
            md_path=md if md.exists() else None,
        )


@dataclass
class SteeringDoc:
    id: str
    file: str
    priority: str
    scope: str
    path: Path

    @classmethod
    def from_yaml(cls, raw: dict) -> SteeringDoc:
        return cls(
            id=raw["id"],
            file=raw["file"],
            priority=raw.get("priority", "medium"),
            scope=raw.get("scope", "all-agents"),
            path=STEERING_DIR / raw["file"],
        )


# ── loaders ────────────────────────────────────────────────────


def load_skills() -> list[Skill]:
    with open(SKILLS_REGISTRY) as f:
        raw = yaml.safe_load(f)
    return [Skill.from_yaml(s) for s in raw.get("skills", [])]


def load_powers() -> list[Power]:
    with open(POWERS_INDEX) as f:
        raw = yaml.safe_load(f)
    return [Power.from_yaml(p) for p in raw.get("powers", [])]


def load_steering() -> list[SteeringDoc]:
    with open(STEERING_INDEX) as f:
        raw = yaml.safe_load(f)
    return [SteeringDoc.from_yaml(d) for d in raw.get("docs", [])]


# ── IO helpers ─────────────────────────────────────────────────


def write_generated(path: Path, content: str, header: str | None = None) -> None:
    """Write *content* to *path*, creating parent dirs."""
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = f"{header}\n\n{content}" if header else content
    path.write_text(payload)


def read_json(path: Path) -> dict:
    with open(path) as f:
        return json.load(f)


def write_json(path: Path, data: dict, *, indent: int = 2) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f, indent=indent)
        f.write("\n")


# ── small utilities ────────────────────────────────────────────


def skill_content(skill: Skill) -> str:
    """Return the body of SKILL.md, or a placeholder if missing."""
    if skill.skill_md_path and skill.skill_md_path.exists():
        return skill.skill_md_path.read_text()
    return f"[MISSING] skills/{skill.id}/SKILL.md not found"


def convention_exists(name: str) -> bool:
    return (CONVENTIONS / f"{name}.md").exists()


def power_exists(name: str, powers: list[Power]) -> bool:
    return any(p.id == name for p in powers)


def mcp_server_exists(name: str) -> bool:
    mcp_json = REPO_ROOT / ".mcp.json"
    if not mcp_json.exists():
        return False
    servers = read_json(mcp_json).get("mcpServers", {})
    return name in servers
